/** Board power for a used GPU listing, matched from the title the seller typed. */
export function inferListingGpuTdp(name: string): number {
  const n = name.toLowerCase().replace(/[-_]/g, " ");
  const rules: [RegExp, number][] = [
    [/rtx\s*5090/, 575],
    [/rtx\s*5080/, 360],
    [/rtx\s*5070\s*ti/, 300],
    [/rtx\s*5070/, 250],
    [/rtx\s*5060\s*ti/, 180],
    [/rtx\s*5060/, 145],
    [/rtx\s*4090/, 450],
    [/rtx\s*4080/, 320],
    [/rtx\s*4070\s*ti/, 285],
    [/rtx\s*4070/, 200],
    [/rtx\s*4060\s*ti/, 160],
    [/rtx\s*4060/, 115],
    [/rtx\s*3090\s*ti/, 450],
    [/rtx\s*3090/, 350],
    [/rtx\s*3080\s*ti/, 350],
    [/rtx\s*3080/, 320],
    [/rtx\s*3070\s*ti/, 290],
    [/rtx\s*3070/, 220],
    [/rtx\s*3060\s*ti/, 200],
    [/rtx\s*3060/, 170],
    [/rtx\s*3050/, 115],
    [/rtx\s*2080\s*ti/, 250],
    [/rtx\s*2080/, 215],
    [/rtx\s*2070/, 175],
    [/rtx\s*2060\s*super/, 175],
    [/rtx\s*2060/, 160],
    [/gtx\s*1660\s*ti/, 120],
    [/gtx\s*1660\s*super/, 125],
    [/gtx\s*1660/, 120],
    [/gtx\s*1650/, 75],
    [/gtx\s*1080\s*ti/, 180],
    [/gtx\s*1080/, 180],
    [/gtx\s*1070/, 150],
    [/gtx\s*1060/, 120],
    [/gtx\s*1050\s*ti/, 75],
    [/rx\s*7900/, 300],
    [/rx\s*7800/, 263],
    [/rx\s*7700/, 245],
    [/rx\s*7600/, 165],
    [/rx\s*6900/, 300],
    [/rx\s*6800\s*xt/, 300],
    [/rx\s*6800/, 250],
    [/rx\s*6700\s*xt/, 230],
    [/rx\s*6700/, 175],
    [/rx\s*6650\s*xt/, 180],
    [/rx\s*6600/, 132],
    [/rx\s*6500/, 107],
    [/rx\s*6400/, 53],
    [/rx\s*580/, 185],
    [/rx\s*570/, 150],
    [/rx\s*560/, 80],
    [/rx\s*550/, 50],
  ];
  for (const [pattern, watts] of rules) {
    if (pattern.test(n)) return watts;
  }
  return 180;
}
